# Understat season = start year integer, e.g. 2023 = 2023-24
# Map from our "2425" format → Understat "2024"
def our_season_to_understat(code: str) -> int:
    """
    Convert our season code to Understat's start-year integer.

    Handles both formats:
      '2425'  → 2024  (football-data.co.uk style: last 2 digits of each year)
      '2024'  → 2024  (update_data.py style: full 4-digit start year)
      '24'    → 2024  (short form)
    """
    code = str(code).strip()
    if len(code) == 4 and code.isdigit():
        year = int(code)
        # If it looks like a full year (2018–2030), use directly
        if 2010 <= year <= 2035:
            return year
        # Otherwise treat as 'XXYY' → 20XX
        return 2000 + int(code[:2])
    if len(code) == 2:
        return 2000 + int(code)
    # Fallback
    return int(code[:4])

