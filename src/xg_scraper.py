def update_xg_incremental(league_key: "str | None" = None) -> pd.DataFrame:
    """
    Fetch only the current season's xG data and append to cached parquet.
    Call this daily/weekly to keep xG data fresh without re-scraping all history.

    Returns:
        Updated combined xG DataFrame.
    """
    current_year = our_season_to_understat(SEASONS.CURRENT)
    leagues      = [league_key] if league_key else list(UNDERSTAT_LEAGUE_MAP.keys())

    new_frames = []
    for lk in leagues:
        df = fetch_league_xg(lk, current_year)
        if df is not None:
            new_frames.append(df)

    if not new_frames:
        logger.warning("No new xG data fetched.")
        try:
            return load_xg_data()
        except FileNotFoundError:
            return pd.DataFrame()

    new_data = pd.concat(new_frames, ignore_index=True)

    # Load existing and merge (overwrite current season)
    try:
        existing = load_xg_data()
        existing = existing[existing["season_year"] != current_year]
        combined = pd.concat([existing, new_data], ignore_index=True)
    except FileNotFoundError:
        combined = new_data

    combined.sort_values(["league_key", "date"], inplace=True)
    combined.reset_index(drop=True, inplace=True)
    save_xg_data(combined)

    logger.info(f"xG incremental update complete: {len(new_data):,} new records")
    return combined


