"""
xg_scraper.py — Fetch xG Data from Understat
==============================================
PURPOSE:
    Scrape match-level xG (expected goals) for both teams from Understat.com
    and merge into the master DataFrame as new features.

WHY xG MATTERS:
    Goals are noisy. A team winning 1-0 on 0.3 xG vs 2.4 xG opponent was lucky.
    Rolling xG averages capture *quality* of chances created/conceded, not just
    results. This is the single most predictive freely-available football metric
    that isn't already fully priced by bookmakers.

DATA PIPELINE:
    Understat → raw JSON (embedded in HTML) → per-match xG DataFrame
    → merge onto master parquet by (date, home_team, away_team)
    → add rolling xG features (5-game window, home/away split)

OUTPUTS added to master DataFrame:
    home_xg            : xG generated by home team this match
    away_xg            : xG generated by away team this match
    home_xg_roll5      : Rolling 5-game avg xG FOR (home perspective)
    away_xg_roll5      : Rolling 5-game avg xG FOR (away perspective)
    home_xga_roll5     : Rolling 5-game avg xG AGAINST (home perspective)
    away_xga_roll5     : Rolling 5-game avg xG AGAINST (away perspective)
    xg_diff_roll5      : home_xg_roll5 - away_xg_roll5 (strength indicator)
    home_xg_overperform: home_goals - home_xg (luck indicator, regresses to 0)
    away_xg_overperform: away_goals - away_xg

UNDERSTAT LEAGUES:
    EPL     → "EPL"
    LA_LIGA → "La_liga"
    SERIE_A → "Serie_A"
    LIGUE_1 → "Ligue_1"
    BUNDESLIGA → "Bundesliga" (add to LEAGUES config if needed)

USAGE:
    python src/xg_scraper.py                  ← fetch all leagues, all seasons
    python src/xg_scraper.py --league EPL     ← single league
    python src/xg_scraper.py --season 2024    ← single season (Understat uses YYYY)

    from src.xg_scraper import add_xg_features
    master_df = add_xg_features(master_df)    ← merge into existing DataFrame

FIXES:
    - Pylance reportArgumentType: engine="pyarrow" removed from read_parquet()
      calls (lines 460, 739). pandas auto-detects pyarrow at runtime; the
      Pylance stub for read_parquet only declares 'auto'|'fastparquet' which
      triggers a false-positive type error. Dropping the kwarg is the cleanest
      solution — behaviour is identical.
"""

